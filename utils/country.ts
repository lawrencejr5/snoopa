/**
 * Returns the full country name for an ISO 3166-1 alpha-2 code (e.g. "NG" -> "Nigeria").
 * Guaranteed to return full name even on Hermes Android where Intl.DisplayNames is missing.
 */
export function getCountryName(code: string | undefined | null): string {
  if (!code) return "";
  const upper = code.trim().toUpperCase();
  if (ISO_COUNTRY_NAMES[upper]) {
    return ISO_COUNTRY_NAMES[upper];
  }
  try {
    if (typeof Intl !== "undefined" && (Intl as any).DisplayNames) {
      const displayNames = new (Intl as any).DisplayNames(["en"], {
        type: "region",
      });
      const name = displayNames.of(upper);
      if (name) return name;
    }
  } catch {
    // fallback
  }
  return upper;
}

