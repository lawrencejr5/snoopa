export function getCountryCodeFromTimeZone(tz?: string): string | undefined {
  let resolvedTz = tz;
  if (!resolvedTz) {
    try {
      resolvedTz = Intl.DateTimeFormat().resolvedOptions().timeZone;
    } catch {
      return undefined;
    }
  }
  if (!resolvedTz) return undefined;
  return TIMEZONE_TO_COUNTRY[resolvedTz];
}
